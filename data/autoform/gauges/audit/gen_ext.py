#!/usr/bin/env python3
"""Generator for gauges/audit/probes_ext.v (method (2) of ASSUMPTIONS.md A130).

`gauges` formalizes closed real intervals over an ABSTRACT `R : realType`.
mathcomp's realType is built on classical (boolp) axioms, so arithmetic on
its literals does not reduce under vm_compute the way it would for a
computable type: `(9 : R) - 5` and `(4 : R)` are only *propositionally*
equal (via mathcomp lemmas such as `natrB`/`natrD`), never *definitionally*
equal, so a literal `vm_compute; reflexivity` probe is unusable here. This
is exactly the case flagged in A130 ("Where computation is unavailable
(gauges) the file records what could be pinned and what could not").

Adaptation actually used, in place of vm_compute:
  - Gauge.v's five names (gauge, lo, hi, inside, width) are pinned by
    spec.md with an EXACT formula (not just a type signature), so they can
    be unfolded and their arithmetic consequences proved by generic
    mathcomp order/ring lemmas (`natrB`, `natrD`, `ler_nat`, `opprK`, ...).
    This script emits one such Example per concrete (lo, hi) instance,
    picking the proof-tactic template by the sign pattern of (lo, hi)
    (nonneg / straddles 0 / both negative) -- three fixed, hand-verified
    templates, instantiated many times over a numeral table below.
  - Ops.v's three names (gplus, gneg, gscale) are pinned by spec.md ONLY
    by type signature (the Minkowski-sum/reflection/scale formulas are
    prose, not "exact"), so this script does not assume a representation.
    Instead it proves three general "value" lemmas straight from the
    required Sound.v + Width.v lemmas (soundness at the two endpoints of a
    nonempty gauge, sandwiched by the width equation) -- so
    `lo (gplus g h) = lo g + lo h` etc. hold for ANY submission whose
    required lemmas type-check, not only one shaped like the reference.
    These lemmas are then instantiated on concrete gauge pairs.
  - Every "expected value" below is the actual sum/negation/product of the
    picked bounds (Python computes it, never hand-typed as an unrelated
    literal), and the whole file must first compile against the reference
    build (well-posedness rule enforced by validate_ref() below).

Usage:
    python3 gen_ext.py            # writes probes_ext.v next to this script
    python3 gen_ext.py --check REFDIR   # also compiles it against REFDIR
                                          (a built theories/ dir, i.e.
                                          .../reference/_build/default/theories)
"""
import argparse
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "probes_ext.v"

HEADER = """From TaskLib Require Import Gauge Ops Sound Width.
From mathcomp Require Import all_ssreflect all_algebra.
From mathcomp Require Import reals.
Import Order.TTheory GRing.Theory Num.Theory.
Local Open Scope ring_scope.

(* ================================================================== *)
(* Generated by gen_ext.py -- see the module docstring there for the   *)
(* method note (why this file does not use vm_compute).                *)
(* ================================================================== *)
"""

SECTION1 = """
(* ===== Section 1: exact-formula pins (Gauge.v) =====================
   Gauge.v's five names have an EXACT required formula in spec.md, not
   just a type signature, so these hold for any conforming submission. *)

Example e_lo_formula : forall (R : realType) (a b : R),
  Gauge.lo ((a, b) : Gauge.gauge R) = a.
Proof. by []. Qed.

Example e_hi_formula : forall (R : realType) (a b : R),
  Gauge.hi ((a, b) : Gauge.gauge R) = b.
Proof. by []. Qed.

Example e_inside_formula : forall (R : realType) (x : R) (g : Gauge.gauge R),
  Gauge.inside x g <-> Gauge.lo g <= x /\\ x <= Gauge.hi g.
Proof. by []. Qed.

Example e_width_formula : forall (R : realType) (g : Gauge.gauge R),
  Gauge.width g = Gauge.hi g - Gauge.lo g.
Proof. by []. Qed.
"""

SECTION3 = """
(* ===== Section 3: Ops.v derived-value lemmas (generic, submission- =
   agnostic: proved only from the required Sound.v + Width.v lemmas,
   never from an assumed internal representation of gplus/gneg/gscale) *)

Lemma sandwich {R : realType} {A B p q : R} :
  A <= p -> q <= B -> B - A = q - p -> p = A /\\ q = B.
Proof.
move=> a1 b2 wc'.
have hq : q = B - A + p. by rewrite wc' subrK.
have b2' : p + (B - A) <= B. by rewrite addrC -hq.
have hpA : p <= A. by rewrite -(subKr B A) lerBrDr.
have eqAp : A = p. by apply: le_anti; apply/andP; split=> //.
have eqBq : B = q. by rewrite hq -eqAp subrK.
split; [exact: esym eqAp | exact: esym eqBq].
Qed.

Lemma h_gplus_value (R : realType) (g h : Gauge.gauge R) :
  Gauge.lo g <= Gauge.hi g -> Gauge.lo h <= Gauge.hi h ->
  Gauge.lo (Ops.gplus g h) = Gauge.lo g + Gauge.lo h /\\
  Gauge.hi (Ops.gplus g h) = Gauge.hi g + Gauge.hi h.
Proof.
move=> hg hh.
have hlo : Gauge.inside (Gauge.lo g) g by split=> //; exact: lexx.
have hhi : Gauge.inside (Gauge.hi g) g by split=> //; exact: lexx.
have hlo' : Gauge.inside (Gauge.lo h) h by split=> //; exact: lexx.
have hhi' : Gauge.inside (Gauge.hi h) h by split=> //; exact: lexx.
have [a1 _] := @Sound.gplus_sound _ _ _ _ _ hlo hlo'.
have [_ b2] := @Sound.gplus_sound _ _ _ _ _ hhi hhi'.
have wc := @Width.width_gplus _ g h.
rewrite /Gauge.width in wc.
have regroup : (Gauge.hi g - Gauge.lo g) + (Gauge.hi h - Gauge.lo h)
             = (Gauge.hi g + Gauge.hi h) - (Gauge.lo g + Gauge.lo h).
  by rewrite addrACA opprD.
have wc' : Gauge.hi (Ops.gplus g h) - Gauge.lo (Ops.gplus g h)
         = (Gauge.hi g + Gauge.hi h) - (Gauge.lo g + Gauge.lo h).
  by rewrite wc regroup.
have [e1 e2] := sandwich a1 b2 wc'.
split; [exact: esym e1 | exact: esym e2].
Qed.

Lemma h_gneg_value (R : realType) (g : Gauge.gauge R) :
  Gauge.lo g <= Gauge.hi g ->
  Gauge.lo (Ops.gneg g) = - Gauge.hi g /\\ Gauge.hi (Ops.gneg g) = - Gauge.lo g.
Proof.
move=> hg.
have hlo : Gauge.inside (Gauge.lo g) g by split=> //; exact: lexx.
have hhi : Gauge.inside (Gauge.hi g) g by split=> //; exact: lexx.
have [a1 _] := @Sound.gneg_sound _ _ _ hhi.
have [_ b2] := @Sound.gneg_sound _ _ _ hlo.
have wc := @Width.width_gneg _ g.
rewrite /Gauge.width in wc.
have negid : (- Gauge.lo g) - (- Gauge.hi g) = Gauge.hi g - Gauge.lo g.
  by rewrite opprK addrC.
have wc' : Gauge.hi (Ops.gneg g) - Gauge.lo (Ops.gneg g) = (- Gauge.lo g) - (- Gauge.hi g).
  by rewrite wc -negid.
have [e1 e2] := sandwich a1 b2 wc'.
split; [exact: esym e1 | exact: esym e2].
Qed.

Lemma h_gscale_value (R : realType) (c : R) (g : Gauge.gauge R) :
  0 <= c -> Gauge.lo g <= Gauge.hi g ->
  Gauge.lo (Ops.gscale c g) = c * Gauge.lo g /\\ Gauge.hi (Ops.gscale c g) = c * Gauge.hi g.
Proof.
move=> hc hg.
have hlo : Gauge.inside (Gauge.lo g) g by split=> //; exact: lexx.
have hhi : Gauge.inside (Gauge.hi g) g by split=> //; exact: lexx.
have [a1 _] := @Sound.gscale_sound _ _ _ _ hc hlo.
have [_ b2] := @Sound.gscale_sound _ _ _ _ hc hhi.
have wc := @Width.width_gscale _ c g.
rewrite /Gauge.width in wc.
have wc' : Gauge.hi (Ops.gscale c g) - Gauge.lo (Ops.gscale c g) = c * Gauge.hi g - c * Gauge.lo g.
  by rewrite wc mulrBr.
have [e1 e2] := sandwich a1 b2 wc'.
split; [exact: esym e1 | exact: esym e2].
Qed.
"""

# ---------------------------------------------------------------------
# Section 2: width + nonemptiness table, table-driven over three sign
# cases (each case is one hand-verified proof template, instantiated
# many times).  "tag" must be a legal Rocq identifier fragment.
# ---------------------------------------------------------------------


def tag_of(a, b):
    def t(n):
        return f"n{-n}" if n < 0 else str(n)
    return f"{t(a)}_{t(b)}"


# ---------------------------------------------------------------------
# Numeral-comparison helpers.  mathcomp's ring_scope gives "0" and "1"
# their OWN dedicated notations (bound directly to GRing.zero/GRing.one),
# while every literal >= 2 goes through the generic `n%:R` (natmul)
# Number Notation. `ler_nat`/`ltr_nat` only fire on the latter, so any
# comparison touching a literal 0 or 1 needs the dedicated bridge lemma
# instead (`lexx`, `ler01`, `ler0n`, `ler1n`, ...) -- these three
# helpers pick the right one so every table entry below (which does
# include several 0s and 1s) gets a tactic that actually applies.
# ---------------------------------------------------------------------


def nonneg_pf(n):
    """Direct proof term for `0 <= (n:R)`, n >= 0."""
    if n == 0:
        return "lexx"
    if n == 1:
        return "ler01"
    return "ler0n"


def le_term(x, y):
    """Full tactic proving `(x:R) <= (y:R)` given x <= y (both >= 0)."""
    if x == y:
        return "exact: lexx"
    if x == 0:
        return "exact: ler01" if y == 1 else "exact: ler0n"
    if x == 1:
        return "by rewrite ler1n"
    return "by rewrite ler_nat"


def lt_term(x, y):
    """Full tactic proving `(x:R) < (y:R)` given x < y (both >= 0)."""
    if x == 0:
        return "exact: ltr01" if y == 1 else "by rewrite ltr0n"
    if x == 1:
        return "by rewrite ltr1n"
    return "by rewrite ltr_nat"


def refute_le(x, y, hyp="h"):
    """Tactic block deriving False from `{hyp} : (x:R) <= (y:R)` in
    context, given the true fact y < x (both x, y >= 0)."""
    return (f"have hlt : ({y}:R) < {x}. {lt_term(y, x)}.\n"
            f"by rewrite (lt_geF hlt) in {hyp}.")


CASE_A = [  # 0 <= a <= b
    (0, 2), (0, 5), (1, 1), (2, 2), (3, 3), (0, 100), (5, 9), (10, 20),
    (7, 7), (1, 10), (2, 50), (0, 1), (4, 12), (6, 6), (8, 8), (9, 9),
    (15, 30), (20, 20), (1, 2), (3, 20),
]

CASE_B = [  # a = -A < 0 <= b = B, A, B > 0
    (-3, 7), (-1, 1), (-5, 5), (-10, 3), (-2, 8), (-7, 2), (-1, 100),
    (-50, 1), (-4, 4), (-6, 9),
]

CASE_C = [  # a = -A <= b = -B < 0, A >= B > 0
    (-7, -3), (-5, -1), (-10, -2), (-9, -4), (-2, -1), (-100, -1),
    (-6, -6), (-20, -5), (-8, -2), (-30, -10),
]


def emit_width_and_ne(a, b):
    tag = tag_of(a, b)
    out = []
    if a >= 0 and b >= 0:
        w = b - a
        out.append(f"""Example e_width_{tag} : forall R : realType,
  Gauge.width (({a},{b}) : Gauge.gauge R) = {w}.
Proof.
move=> R. rewrite /Gauge.width/Gauge.lo/Gauge.hi/=.
by rewrite -(natrB _ (isT : ({a}<={b})%N)).
Qed.
""")
        out.append(f"""Example e_ne_{tag} : forall R : realType,
  Gauge.lo (({a},{b}):Gauge.gauge R) <= Gauge.hi ({a},{b}).
Proof. move=> R. rewrite /Gauge.lo/Gauge.hi/=. {le_term(a, b)}. Qed.
""")
    elif a < 0 <= b:
        A, B = -a, b
        w = A + B
        out.append(f"""Example e_width_{tag} : forall R : realType,
  Gauge.width (({a},{b}) : Gauge.gauge R) = {w}.
Proof.
move=> R. rewrite /Gauge.width/Gauge.lo/Gauge.hi/=.
rewrite opprK -(natrD _ {B} {A}). by [].
Qed.
""")
        out.append(f"""Example e_ne_{tag} : forall R : realType,
  Gauge.lo (({a},{b}):Gauge.gauge R) <= Gauge.hi ({a},{b}).
Proof.
move=> R. rewrite /Gauge.lo/Gauge.hi/=.
apply: (le_trans (y:=0)); [rewrite oppr_le0; exact: {nonneg_pf(A)} | exact: {nonneg_pf(B)}].
Qed.
""")
    else:  # both negative, a = -A <= b = -B < 0, A >= B > 0
        A, B = -a, -b
        w = A - B
        out.append(f"""Example e_width_{tag} : forall R : realType,
  Gauge.width (({a},{b}) : Gauge.gauge R) = {w}.
Proof.
move=> R. rewrite /Gauge.width/Gauge.lo/Gauge.hi/=.
rewrite opprK addrC -(natrB _ (isT : ({B}<={A})%N)). by [].
Qed.
""")
        out.append(f"""Example e_ne_{tag} : forall R : realType,
  Gauge.lo (({a},{b}):Gauge.gauge R) <= Gauge.hi ({a},{b}).
Proof. move=> R. rewrite /Gauge.lo/Gauge.hi/= lerN2. {le_term(B, A)}. Qed.
""")
    return "".join(out)


def emit_boundary_case_a(a, b):
    """Boundary membership + outside points, for case-A pairs (0 <= a <= b).
    `below` always tests the fixed point -1 (uniform in a, b: -1 < 0 <= a
    always), so it needs no bucket-casing beyond nonneg_pf(a); `above`
    tests b+1, refuted via the bucket-independent fact b < b+1."""
    tag = tag_of(a, b)
    return f"""Example e_inside_lo_{tag} : forall R : realType, Gauge.inside ({a}:R) ({a},{b}).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/=.
split; [exact: lexx | {le_term(a, b)}].
Qed.

Example e_inside_hi_{tag} : forall R : realType, Gauge.inside ({b}:R) ({a},{b}).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/=.
split; [{le_term(a, b)} | exact: lexx].
Qed.

Example e_outside_above_{tag} : forall R : realType, ~ Gauge.inside ({b + 1}:R) ({a},{b}).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/= => -[_ h].
have hlt : ({b}:R) < {b + 1}. {lt_term(b, b + 1)}.
by rewrite (lt_geF hlt) in h.
Qed.

Example e_outside_below_{tag} : forall R : realType, ~ Gauge.inside (-1:R) ({a},{b}).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/= => -[h _].
have h0 : (0:R) <= {a}. exact: {nonneg_pf(a)}.
have h1 : (0:R) <= -1. exact: le_trans h0 h.
move: h1. rewrite oppr_ge0. by rewrite (lt_geF ltr01).
Qed.
"""


# One hand-verified boundary/outside example each for case B and case C,
# on the first table entry of each (the general pattern needs a case
# split on which side of 0 the tested point falls, so it is not
# re-derived generically here -- see the README's "Not covered" note).
BOUNDARY_B = """
Example e_outside_below_n3_7 : forall R : realType, ~ Gauge.inside (-4:R) (-3,7).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/= => -[h _].
move: h; rewrite lerN2. by rewrite ler_nat.
Qed.
"""

BOUNDARY_C = """
Example e_outside_above_n7_n3 : forall R : realType, ~ Gauge.inside (-2:R) (-7,-3).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/= => -[_ h].
move: h; rewrite lerN2. by rewrite ler_nat.
Qed.
"""

# ---------------------------------------------------------------------
# Section 4: concrete applications of the Section-3 value lemmas, on
# pairs/gauges drawn from the (already-proved-nonempty) tables above.
# ---------------------------------------------------------------------

GPLUS_PAIRS = [(0, 2, 0, 2), (5, 9, -3, 7), (-7, -3, 5, 9), (1, 10, -1, 1),
               (2, 50, -5, 5), (0, 100, -10, 3)]
GNEG_GAUGES = [(5, 9), (-3, 7), (-7, -3), (0, 2), (1, 10), (-50, 1)]
GSCALE_INSTANCES = [(2, 5, 9), (0, -3, 7), (3, 0, 2), (5, 1, 10),
                     (1, -7, -3), (2, -10, 3)]


def emit_gplus(a, b, c, d):
    tag = f"{tag_of(a, b)}__{tag_of(c, d)}"
    return f"""Example e_gplus_{tag} : forall R : realType,
  Gauge.lo (Ops.gplus ({a},{b}) ({c},{d}) : Gauge.gauge R) = {a} + ({c}) /\\
  Gauge.hi (Ops.gplus ({a},{b}) ({c},{d}) : Gauge.gauge R) = {b} + {d}.
Proof.
move=> R. apply: h_gplus_value; [exact: e_ne_{tag_of(a, b)} | exact: e_ne_{tag_of(c, d)}].
Qed.
"""


def emit_gneg(a, b):
    tag = tag_of(a, b)
    return f"""Example e_gneg_{tag} : forall R : realType,
  Gauge.lo (Ops.gneg ({a},{b}) : Gauge.gauge R) = - ({b}:R) /\\
  Gauge.hi (Ops.gneg ({a},{b}) : Gauge.gauge R) = - ({a}:R).
Proof. move=> R. apply: h_gneg_value. exact: e_ne_{tag}. Qed.
"""


def emit_gscale(c, a, b):
    tag = f"{c}__{tag_of(a, b)}"
    c_pf = f"exact: {nonneg_pf(c)}"
    return f"""Example e_gscale_{tag} : forall R : realType,
  Gauge.lo (Ops.gscale {c} ({a},{b}) : Gauge.gauge R) = {c} * ({a}) /\\
  Gauge.hi (Ops.gscale {c} ({a},{b}) : Gauge.gauge R) = {c} * {b}.
Proof. move=> R. apply: h_gscale_value; [{c_pf} | exact: e_ne_{tag_of(a, b)}]. Qed.
"""


SECTION5 = """
(* ===== Section 5: non-vacuity witnesses for the Sound.v hypotheses ===
   Show the hypotheses of gplus_sound/gneg_sound/gscale_sound are
   simultaneously satisfiable on a concrete instance under the
   submission's OWN required definitions, so a submission that proves
   these lemmas vacuously (e.g. because `inside` never holds) fails here. *)

Example w_gplus_sound : forall R : realType,
  Gauge.inside (5:R) (5,9) /\\ Gauge.inside (-3:R) (-3,7).
Proof.
move=> R; split; rewrite e_inside_formula /Gauge.lo/Gauge.hi/=.
- split; [exact: lexx | exact: ler_nat].
- split; [exact: lexx | apply: (le_trans (y:=0));
    [rewrite oppr_le0; exact: ler0n | exact: ler0n]].
Qed.

Example w_gneg_sound : forall R : realType, Gauge.inside (5:R) (5,9).
Proof.
move=> R. rewrite e_inside_formula /Gauge.lo/Gauge.hi/=.
split; [exact: lexx | exact: ler_nat].
Qed.

Example w_gscale_sound : forall R : realType, 0 <= (2:R) /\\ Gauge.inside (5:R) (5,9).
Proof.
move=> R; split; first exact: ler0n.
rewrite e_inside_formula /Gauge.lo/Gauge.hi/=.
split; [exact: lexx | exact: ler_nat].
Qed.
"""


def build():
    parts = [HEADER, SECTION1]

    parts.append("\n(* ===== Section 2: width + nonemptiness, table-driven over the three "
                 "sign cases of (lo, hi) ===== *)\n")
    for a, b in CASE_A:
        parts.append(emit_width_and_ne(a, b))
    for a, b in CASE_B:
        parts.append(emit_width_and_ne(a, b))
    for a, b in CASE_C:
        parts.append(emit_width_and_ne(a, b))

    parts.append("\n(* boundary membership + outside points *)\n")
    for a, b in CASE_A:
        parts.append(emit_boundary_case_a(a, b))
    parts.append(BOUNDARY_B)
    parts.append(BOUNDARY_C)

    parts.append(SECTION3)

    parts.append("\n(* ===== Section 4: concrete applications of the Section-3 value "
                 "lemmas ===== *)\n")
    for a, b, c, d in GPLUS_PAIRS:
        parts.append(emit_gplus(a, b, c, d))
    for a, b in GNEG_GAUGES:
        parts.append(emit_gneg(a, b))
    for c, a, b in GSCALE_INSTANCES:
        parts.append(emit_gscale(c, a, b))

    parts.append(SECTION5)
    return "".join(parts)


def validate_ref(theory_dir: Path):
    """Compile the generated file against a built reference theories/ dir."""
    rocq = None
    for cand in ("rocq", "/Users/gbaudart/Project/llm4rocq/rocq-tools/_opam/bin/rocq"):
        try:
            subprocess.run([cand, "--version"], capture_output=True, check=True)
            rocq = cand
            break
        except Exception:
            continue
    if rocq is None:
        print("rocq not found on PATH; skipping --check", file=sys.stderr)
        return False
    cmd = [rocq, "compile", "-Q", str(theory_dir), "TaskLib", str(OUT)]
    res = subprocess.run(cmd, cwd=str(OUT.parent), capture_output=True, text=True)
    sys.stdout.write(res.stdout)
    sys.stderr.write(res.stderr)
    return res.returncode == 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", metavar="THEORY_DIR", default=None,
                     help="also compile the result against this built "
                          "theories/ directory (e.g. reference/_build/default/theories)")
    args = ap.parse_args()

    OUT.write_text(build())
    print(f"wrote {OUT} ({len(OUT.read_text().splitlines())} lines)")

    if args.check:
        ok = validate_ref(Path(args.check))
        print("compiles against reference: %s" % ("OK" if ok else "FAILED"))
        sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
