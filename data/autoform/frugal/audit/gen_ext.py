#!/usr/bin/env python3
"""Generate probes_ext.v for the "frugal" autoform task (audit method 2).

Builds the task's reference/ solution, evaluates a battery of table-driven
`vm_compute` queries against the REQUIRED-NAME functions (Carrier.meld,
Carrier.chain, Carrier.ceq, Carrier.top, Carrier.one, Mat2.Mat/a00/a01/a10/
a11, Mat2.mmul) on hundreds of concrete inputs, captures Rocq's own printed
normal forms, and emits `probes_ext.v`: a self-contained file of
`Example ... = <reference-computed value>. Proof. vm_compute; reflexivity.
Qed.` statements (plus one `Theorem` shape pin for `Carrier.ceqP`, which the
original probes.v never exercises).

The expected values are NEVER typed by hand -- they come verbatim from
`rocq compile`'s stdout on the reference build. Re-run with:

    python3 gen_ext.py

from anywhere; all paths are resolved relative to this file. Requires the
project's opam switch (dune + rocq) to be reachable, either at the
hard-coded default path below or on $PATH.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent          # .../data/autoform/frugal/audit
TASK_DIR = HERE.parent                          # .../data/autoform/frugal
REF_SRC = TASK_DIR / "reference"
OUT_FILE = HERE / "probes_ext.v"

DEFAULT_OPAM_BIN = Path("/Users/gbaudart/Project/llm4rocq/rocq-tools/_opam/bin")

PRELUDE = (
    "(* AUTO-GENERATED by gen_ext.py -- do not hand-edit; re-run the script. *)\n"
    "(* Extended, reference-derived probes for the \"frugal\" task (audit *)\n"
    "(* method 2 of ASSUMPTIONS.md A130): table-driven vm_compute pins of *)\n"
    "(* the required names over hundreds of concrete instances, plus one *)\n"
    "(* statement-shape pin for Carrier.ceqP (untested by probes.v).      *)\n"
    "From TaskLib Require Import Carrier Laws Mat2 Main.\n"
    "From mathcomp Require Import all_ssreflect all_algebra.\n"
)

# Each entry: (name, Rocq expression string built only from required names +
# stdlib/mathcomp). The same string is used verbatim (a) inside `Eval
# vm_compute in (...)` against the reference build to obtain the printed
# normal form, and (b) as the LHS of the final `Example name : expr = ....`
# so there is exactly one source of truth for what is being pinned.
QUERIES: list[tuple[str, str]] = [
    # -- meld: full sweep over a symmetric range, plus top-identity on
    # both sides, plus the top/top corner case.
    ("e_meld_sweep",
     "map (fun n => Carrier.meld (Some n) (Some (999 - n))) (iota 0 1000)"),
    ("e_meld_top_left",
     "map (fun n => Carrier.meld Carrier.top (Some n)) (iota 0 500)"),
    ("e_meld_top_right",
     "map (fun n => Carrier.meld (Some n) Carrier.top) (iota 0 500)"),
    ("e_meld_top_top",
     "Carrier.meld Carrier.top Carrier.top"),

    # -- chain: sweep, top-absorption on both sides, one-identity on both
    # sides, plus the top/top corner case.
    ("e_chain_sweep",
     "map (fun n => Carrier.chain (Some n) (Some (2 * n + 1))) (iota 0 1000)"),
    ("e_chain_top_absorb_left",
     "map (fun n => Carrier.chain Carrier.top (Some n)) (iota 0 500)"),
    ("e_chain_top_absorb_right",
     "map (fun n => Carrier.chain (Some n) Carrier.top) (iota 0 500)"),
    ("e_chain_one_left",
     "map (fun n => Carrier.chain Carrier.one (Some n)) (iota 0 500)"),
    ("e_chain_one_right",
     "map (fun n => Carrier.chain (Some n) Carrier.one) (iota 0 500)"),
    ("e_chain_top_top",
     "Carrier.chain Carrier.top Carrier.top"),

    # -- ceq: reflexive, distinct, vs. top, top/top.
    ("e_ceq_refl",
     "map (fun n => Carrier.ceq (Some n) (Some n)) (iota 0 500)"),
    ("e_ceq_diff",
     "map (fun n => Carrier.ceq (Some n) (Some (n + 1))) (iota 0 500)"),
    ("e_ceq_vs_top",
     "map (fun n => Carrier.ceq (Some n) Carrier.top) (iota 0 500)"),
    ("e_ceq_top_top",
     "Carrier.ceq Carrier.top Carrier.top"),

    # -- Mat2 record constructor + all four accessors, over 300 matrices.
    ("e_mat_accessors",
     "map (fun n => let m := Mat2.Mat (Some n) (Some (n + 1)) (Some (n + 2)) (Some (n + 3)) in "
     "(Mat2.a00 m, Mat2.a01 m, Mat2.a10 m, Mat2.a11 m)) (iota 0 300)"),

    # -- Mat2.mmul on two different families of 300 matrices each, one
    # mixing in `top` (None) on the right factor, the other mixing `top`
    # into both factors at different positions, to force meld/chain
    # interaction through the None-absorption and None-identity cases,
    # not just the all-Some arithmetic. Results are projected back to a
    # plain 4-tuple of carrier values through the *required* accessors
    # (Mat2.a00/a01/a10/a11) rather than printed as a raw `mat` record
    # literal: reflexivity on a re-parsed unqualified `{| a00 := ...|}`
    # record literal is not reliable across submissions (a submission may
    # wrap Mat2.v's contents in an inner `Module Mat2.`, which shadows the
    # bare field name `a00` used by Rocq's own pretty-printer, so the
    # printed literal fails to re-elaborate against *that* submission even
    # though `Mat2.a00`/`Mat2.mmul` behave correctly) -- projecting through
    # the qualified accessors sidesteps that and stays within the required
    # names.
    ("e_mmul_table1",
     "map (fun n => let m := Mat2.mmul "
     "(Mat2.Mat (Some n) (Some (n + 1)) (Some (n + 2)) (Some (n + 3))) "
     "(Mat2.Mat (Some (2 * n)) Carrier.top (Some 1) (Some n)) in "
     "(Mat2.a00 m, Mat2.a01 m, Mat2.a10 m, Mat2.a11 m)) (iota 0 300)"),
    ("e_mmul_table2",
     "map (fun n => let m := Mat2.mmul "
     "(Mat2.Mat Carrier.top (Some n) (Some (n + 2)) Carrier.top) "
     "(Mat2.Mat (Some n) Carrier.top Carrier.top (Some (2 * n + 3))) in "
     "(Mat2.a00 m, Mat2.a01 m, Mat2.a10 m, Mat2.a11 m)) (iota 0 300)"),
]

# A statement-shape pin (no computation): probes.v never exercises
# Carrier.ceqP at all. This forces a submission's ceqP to actually have the
# required reflect-typed proof term, the same way probes.v pins the Laws.*
# lemmas.
CEQP_SHAPE = (
    "Theorem e_ceqP : forall x y, reflect (x = y) (Carrier.ceq x y).\n"
    "Proof. exact: Carrier.ceqP. Qed.\n"
)


def find_opam_bin() -> Path:
    if (DEFAULT_OPAM_BIN / "dune").exists():
        return DEFAULT_OPAM_BIN
    for anc in HERE.parents:
        cand = anc / "_opam" / "bin"
        if (cand / "dune").exists():
            return cand
    dune = shutil.which("dune")
    if dune:
        return Path(dune).resolve().parent
    raise RuntimeError("could not locate a dune/rocq opam switch bin dir")


def run(cmd: list[str], cwd: Path, env: dict) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)


def build_theories(src: Path, workdir: Path, env: dict, label: str) -> Path:
    """Copy a dune project (excluding _build) into workdir and build it.
    Returns the built theories/ directory."""
    dst = workdir / label
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("_build"))
    proc = run(["dune", "build", "--root", "."], dst, env)
    if proc.returncode != 0:
        sys.stderr.write(f"--- dune build failed for {label} ---\n{proc.stdout}\n{proc.stderr}\n")
        raise SystemExit(1)
    theories = dst / "_build" / "default" / "theories"
    if not theories.exists():
        raise SystemExit(f"no theories/ produced under {dst}")
    return theories


def eval_queries(theories: Path, workdir: Path, env: dict) -> list[str]:
    """Compile one .v file with an `Eval vm_compute in (...)` per query
    against `theories`, and return the printed normal form for each query,
    in order, as raw Rocq source text (whitespace-collapsed)."""
    genv = workdir / "genq"
    genv.mkdir(exist_ok=True)
    lines = [PRELUDE, ""]
    for _name, expr in QUERIES:
        lines.append(f"Eval vm_compute in ({expr}).")
    (genv / "gen.v").write_text("\n".join(lines) + "\n")

    proc = run(
        ["rocq", "compile", "-Q", str(theories), "TaskLib", "gen.v"],
        genv, env,
    )
    if proc.returncode != 0:
        sys.stderr.write(f"--- rocq compile of query file failed ---\n{proc.stdout}\n{proc.stderr}\n")
        raise SystemExit(1)

    out_lines = proc.stdout.splitlines()
    blocks: list[str] = []
    cur: list[str] = []
    for line in out_lines:
        if re.match(r"^\s*:\s", line):
            blocks.append(" ".join(cur))
            cur = []
        else:
            cur.append(line.strip())
    if cur:
        blocks.append(" ".join(cur))  # tolerate a missing trailing type line

    if len(blocks) != len(QUERIES):
        raise SystemExit(
            f"expected {len(QUERIES)} result blocks from rocq, got {len(blocks)}:\n"
            + proc.stdout
        )

    values = []
    for b in blocks:
        b = b.strip()
        assert b.startswith("="), f"unexpected block (no leading '='): {b!r}"
        b = b[1:].strip()
        b = re.sub(r"\s+", " ", b)
        values.append(b)
    return values


def write_probes_ext(values: list[str]) -> None:
    parts = [PRELUDE, ""]
    for (name, expr), val in zip(QUERIES, values):
        parts.append(f"Example {name} :\n  {expr}\n  = {val}.\nProof. vm_compute; reflexivity. Qed.\n")
    parts.append(CEQP_SHAPE)
    OUT_FILE.write_text("\n".join(parts))


def validate(theories: Path, workdir: Path, env: dict, label: str) -> None:
    chk = workdir / f"check_{label}"
    chk.mkdir(exist_ok=True)
    shutil.copy(OUT_FILE, chk / "probes_ext.v")
    proc = run(
        ["rocq", "compile", "-Q", str(theories), "TaskLib", "probes_ext.v"],
        chk, env,
    )
    if proc.returncode != 0:
        sys.stderr.write(f"--- probes_ext.v FAILED against {label} ---\n{proc.stdout}\n{proc.stderr}\n")
        raise SystemExit(1)
    print(f"probes_ext.v OK against {label}")


def main() -> None:
    opam_bin = find_opam_bin()
    env = dict(os.environ)
    env["PATH"] = f"{opam_bin}{os.pathsep}{env.get('PATH', '')}"

    with tempfile.TemporaryDirectory(prefix="gen_ext_frugal_") as tmp:
        workdir = Path(tmp)
        ref_theories = build_theories(REF_SRC, workdir, env, "reference")
        values = eval_queries(ref_theories, workdir, env)
        write_probes_ext(values)
        print(f"wrote {OUT_FILE} ({len(QUERIES)} vm_compute-derived statements + 1 shape pin)")
        validate(ref_theories, workdir, env, "reference")


if __name__ == "__main__":
    main()
